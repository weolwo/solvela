-- =====================================================================================
-- 活动配置：新增「数据截止时间」
-- 日期：2026-08-30
--
-- 为什么需要它：活动的【参与截止】与【整体结束】经常不是同一个时刻。
-- 常见形态是数据截止比活动结束早 1 天到 1 周 —— 那段时间用来发奖、兑奖、公示，
-- 但不再受理新的参与。此前只有 end_time 一个时刻，这两件事没法分开表达，
-- 运营的做法是把 end_time 提前，代价是活动页跟着提前下线，用户领不到已经中的奖。
--
-- 三个时间窗（判据在 ActivityRuntimeService / 参与入口）：
--   start_time  ── data_end_time ── end_time
--   [   可参与、可领奖   ][  只可领奖、可查看  ][ 已结束 ]
--
-- 允许为空：绝大多数活动不区分这两件事，为空即「与 end_time 相同」，
-- 行为与加这列之前完全一致。刻意不给一个具体默认值 —— 默认值会让「没配」和
-- 「配成和结束时间一样」看起来一模一样，将来想区分就区分不了了。
-- =====================================================================================

ALTER TABLE `t_activity_config`
    ADD COLUMN `data_end_time` datetime DEFAULT NULL
        COMMENT '数据截止时间：此刻起不再受理参与（抽奖/任务累计），但活动仍可见、奖品仍可领到 end_time。为空表示与 end_time 相同'
        AFTER `end_time`;

-- 存量数据不需要回填：为空即等同于 end_time，与加列之前的行为一致。
