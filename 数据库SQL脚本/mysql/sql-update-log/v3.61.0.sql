-- =====================================================================================
-- v3.61.0  任务模板表新增状态列：模板可启停，替代「删除」
-- 撰写：2026-08-15
--
-- 背景：任务模板被 t_task_config.template_code 引用（且是任务运行态取 ui_schema / rule_script 的来源）。
--   删模板会让引用它的任务配置直接断链 —— 向导拉不到模板、运行态取不到规则脚本，
--   而这两处都不是「立刻报错」，是「安静地不再推进」。
--   所以管理端把删除换成启停：禁用后不再出现在向导的可选模板里，已经建好的任务不受影响。
--
-- ⚠️ 默认值给 1（启用）：存量模板都在用，迁移后必须保持可用，不能一刀切成禁用。
-- =====================================================================================

ALTER TABLE `t_task_template`
    ADD COLUMN `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：0-禁用, 1-启用' AFTER `rule_script`;

