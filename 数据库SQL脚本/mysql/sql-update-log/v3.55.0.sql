-- ============================================================================
-- v3.55.0  公开图：可见性由分类决定 + 活动素材分类
-- ============================================================================
--
-- 背景：C 端用户是匿名的，永远带不上 token，所以活动展示图必须能被无鉴权地取到。
-- 而在此之前「谁是公开的」这个问题在代码里没有答案 —— FileAssetService 把每一次上传
-- 都写死成 visibility=1(公开)，同时 FileConfig 又把整个上传目录挂成了免登录静态资源。
-- 两者叠加的结果是：所有文件都匿名可取，包括意见反馈的附件。
--
-- 本次把这件事收口成一条规则：**可见性由分类决定，默认私有**。
--   · 分类上新增 default_visibility，新文件上传时从分类带下来（代码不再写死）
--   · 只有「活动素材」是公开的 —— 它就是给 C 端看的，别的分类没有这个需要
--   · 静态资源映射同步删除，公开文件改走一个会查 visibility 的免登录端点
--
-- ⚠️ 时钟源沿用 v3.38.0 口径：create_time / update_time 由数据库产生，Java 侧不填充。

-- ----------------------------------------------------------------------------
-- ① 分类上挂默认可见性
-- ----------------------------------------------------------------------------
--
-- 默认值取 2(私有) 是刻意的：将来有人加分类却忘了想这件事时，
-- 结果是「图看不见」而不是「附件被公开了」。前者会被立刻发现，后者可能永远不会。

ALTER TABLE `t_file_category`
    ADD COLUMN `default_visibility` tinyint NOT NULL DEFAULT 2 COMMENT '该分类新文件的默认可见性：1公开 2私有' AFTER `sort`;

-- ----------------------------------------------------------------------------
-- ② 活动素材分类
-- ----------------------------------------------------------------------------
--
-- 不指定 category_id，让它自增 —— 各环境拿到的数字不一样，所以代码必须按 category_code
-- 引用它（'ACTIVITY'），这是 v3.53.0 里已经写明的纪律。为此上传接口本次也补了 categoryCode 入参，
-- 前端不再传环境相关的数字 ID。
--
-- category_code 会成为 storageKey 的第一段（activity/202608/10/xxx.png），
-- 将来在 CDN 上按前缀配缓存规则、按前缀配匿名读策略，都靠它。

INSERT INTO `t_file_category` (`category_code`, `category_name`, `category_tag`, `sort`, `default_visibility`)
VALUES ('ACTIVITY', '活动素材', '营销', 5, 1);

-- ----------------------------------------------------------------------------
-- ③ 存量文件一律改成私有
-- ----------------------------------------------------------------------------
--
-- 这一步才是真正把口子收上：存量数据的 visibility 全是 1(公开)，是因为上传处写死了 1，
-- 不代表有人判断过它们该公开。活动素材分类是新建的、还没有文件，所以这里可以无条件全改。
--
-- 影响面：管理端的预览不受影响（走带 token 取字节的那条路）；C 端目前没有。
-- 已经被活动引用着的历史图（如果有）会变成"C 端取不到"，需要运营在展示配置里
-- 重新从活动素材分类选一张 —— 这是数据问题，不是代码问题，改回公开只需 UPDATE 单行。

UPDATE `t_file` SET `visibility` = 2 WHERE `visibility` = 1;

