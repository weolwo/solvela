-- =====================================================================================
-- v3.71.1  状态类两张表的 member_name 放开 NOT NULL（Java 切 memberId 的<b>前置</b>）
-- 撰写：2026-08-22
--
-- 【为什么需要这个文件】
--   v3.71.0 与 v3.72.0 之间原本缺了一步，缺口在两次上线的<b>中间态</b>上：
--
--     · v3.71.0 已执行：member_id 就位，member_name 仍是 NOT NULL 且无默认值
--     · 代码这一版要做的事：状态类（t_member_wallet / t_task_record）<b>不再写 member_name</b>
--       —— 它俩的 member_name 是要被 v3.72.0 删掉的列，Entity 上留着这个字段没有意义
--     · v3.72.0 才 DROP COLUMN，而它<b>必须等代码上线并观察一个版本之后</b>再执行
--
--   于是中间那段时间：Entity 里没有 memberName -> MyBatis-Plus 省略该列 ->
--   MySQL 严格模式撞上「NOT NULL 且无默认值」-> INSERT 直接被拒：
--       Field 'member_name' doesn't have a default value
--   钱包自愈初始化和任务记录创建<b>全部插不进去</b>。
--   这个模式在本项目已经复发过 6 次（见 TaskEventContext 类注释里那份清单），
--   这次是第 7 次，只不过是在迁移编排上犯的。
--
-- 【为什么单独一个文件，不并进 v3.71.0 也不并进 v3.72.0】
--   三个文件的<b>执行时机互不相同</b>，合并任何两个都会做出一个「没有任何时刻可以整体执行」
--   的脚本（v3.71.0 的文件头记着同样的教训）：
--
--     v3.71.0   改库，对旧代码无害        -> 随时可执行（已执行）
--     v3.71.1   本文件，对旧代码无害      -> <b>新代码上线之前</b>执行
--     v3.72.0   删列，对旧代码有害        -> 新代码<b>观察一个版本之后</b>执行
--
--   本文件对旧代码无害：把列放开成可空，旧代码照常往里写值，什么都不会变。
--   所以它可以和 v3.71.0 一样提前执行，不需要停机窗口。
--
-- 【只放开这两张，单据类<b>一张都不动</b>】
--   单据类的 member_name 要留作展示快照，新代码<b>继续写它</b>，
--   保持 NOT NULL 正好能挡住「忘了填快照」。它们的收窄在 v3.72.0。
--
-- ⚠️ ALGORITHM：NOT NULL -> NULL 只能 INPLACE（会重建表），不支持 INSTANT。
--    两张表当前 859 / 1691 行，毫秒级；数据量涨上去之后再执行要走维护窗口。
-- =====================================================================================

ALTER TABLE `t_member_wallet` MODIFY `member_name` varchar(64) NULL COMMENT '会员名【已弃用：关联键是 member_id，本列由 v3.72.0 删除】';
ALTER TABLE `t_task_record`   MODIFY `member_name` varchar(64) NULL COMMENT '会员名【已弃用：关联键是 member_id，本列由 v3.72.0 删除】';


-- -------------------------------------------------------------------------------------
-- 验收：两张表的 member_name 都应当是可空
-- -------------------------------------------------------------------------------------
SELECT TABLE_NAME AS `表`, IS_NULLABLE AS `可空`, COLUMN_TYPE AS `类型`
  FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA = DATABASE()
   AND COLUMN_NAME = 'member_name'
   AND TABLE_NAME IN ('t_member_wallet', 't_task_record');
-- 期望：两行，可空都是 YES。仍是 NO 的话不要上线新代码 —— 一上线就是全量 INSERT 失败。
