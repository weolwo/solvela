-- ============================================================================
-- v3.56.0  去掉「公开/私有」：文件一律公开
-- ============================================================================
--
-- 这是一次**减法**，撤掉 v3.53.0 引入、v3.55.0 才真正启用的 visibility 概念。
--
-- 决策：这个文件模块服务的是活动/任务配置，不是网盘。运营传进来的每一张图，
-- 最终目的都是给 C 端看 —— 而 C 端用户是匿名的，所以「公开」是唯一有意义的状态。
-- 为一个只有一种取值的维度维护一列、一个枚举、一条上传时的判断和一处读取时的分支，
-- 是在为一个不存在的需求付利息。
--
-- 那「不该公开的东西」怎么办？答案是**它们不该进这个模块**：
-- 将来若开放 C 端用户上传（头像、晒单图等），那是一条独立的链路，
-- 要防的是上传本身（配额、审核、鉴黄），不是靠给文件挂一个可见性标记。
-- 把两件事塞进同一张表，只会让两边都做不干净。
--
-- 存量数据不做任何迁移：dev 库里都是开发期的测试文件，该删的直接删。
--
-- ⚠️ 时钟源沿用 v3.38.0 口径：create_time / update_time 由数据库产生，Java 侧不填充。

-- ----------------------------------------------------------------------------
-- ① 去掉两列
-- ----------------------------------------------------------------------------

ALTER TABLE `t_file` DROP COLUMN `visibility`;

ALTER TABLE `t_file_category` DROP COLUMN `default_visibility`;

