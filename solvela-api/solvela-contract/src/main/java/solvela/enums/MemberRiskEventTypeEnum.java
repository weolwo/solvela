package solvela.enums;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 风控事件类型。取值与 {@code t_member_risk_rule.event_type}、{@code t_member_risk_event.event_type} 一致。
 *
 * <h3>它同时是「规则属于哪个场景」</h3>
 * 一条规则只属于一个场景（{@code t_member_risk_rule.event_type}），而且<b>以代码为准、与表核对</b>：
 * 把密码冷却那条规则在表里改成注册场景，它会在一个压根没有密码的流程里执行 ——
 * 所以不一致时启动即失败，与「阶段」同一个做法（见 {@code RiskRuleRegistry.toConfig}）。
 *
 * <p>要让同一种判断覆盖两个场景（比如 IP 黑名单），就写两条规则、两行配置 ——
 * 🔴 <b>刻意不做「一条规则适用多个场景」</b>：那会让一次改阈值同时影响登录和注册，
 * 而两边的量级、误伤面、可接受的处置完全不同。两行配置看着啰嗦，但它让「改这个数会影响谁」
 * 在表上一眼看得见。
 *
 * @Date 2026-10-15
 */
@Getter
@AllArgsConstructor
public enum MemberRiskEventTypeEnum implements BaseEnum {

    LOGIN(1, "登录"),

    /** 凭票验码。是另一个请求，单独一行流水，{@code ref_event_id} 指回签票的那次登录 */
    LOGIN_VERIFY(2, "登录二次验证"),

    /**
     * 注册。
     *
     * <h3>它只有前置一个决策点</h3>
     * 登录分前后两段是因为「密码对不对」把可用的信号分成了两半。注册没有这条分界线 ——
     * 验证码验过之后账号就建出来了，没有「验完再判一次」的位置。
     *
     * <h3>🔴 注册场景的处置只能是放行 / 限流 / 拒绝</h3>
     * 滑块和 OTP 在这里没有落点：滑块票由网关在<b>发码那一步</b>核销，
     * 而注册本身已经验过一次验证码了，再要一道 OTP 等于让同一个邮箱收两封信。
     * 所以注册规则的参数校验会拒绝配成滑块或 OTP（见各规则的 {@code validate}）。
     */
    REGISTER(3, "注册"),

    /**
     * 重置密码（自助找回）。
     *
     * <h3>它和注册同形：只有前置，处置只能是放行 / 限流 / 拒绝</h3>
     * 验证码验过就改密码了，没有「验完再判一次」的位置；而滑块票在发码那一步核销，
     * 重置接口本身收不到票，再要一道 OTP 等于让同一个邮箱收两封信。
     *
     * <h3>🔴 但它是整条账号安全链上<b>后果最重</b>的一个场景</h3>
     * 重置成功 = 改密 + 吊销全部会话 + 撤销设备信任 + 解开资产出口冻结。
     * 也就是说：挡错一个真人，他丢的是「找回账号」这条路本身（而他已经进不去了）；
     * 放过一个坏人，原主连验证码登录都进不来。
     *
     * <p>所以这个场景的两条新阈值<b>先陪跑</b>（见 §12.6），
     * 而「新绑的联系方式 7 天内不能用来找回密码」刻意<b>不做成规则</b> ——
     * 规则意味着页面上有一个能把它关掉的下拉框。
     */
    RESET_PASSWORD(4, "重置密码"),

    /**
     * 资产出口（加收货地址、充话费 —— 把本站资产带出账号的那两条路）。
     *
     * <h3>🔴 它是唯一一个「风控能要求核身」的非登录场景</h3>
     * 注册、重置密码那两条链路上没有核身的落点（票在发码那一步核销，接口本身已经验过一次码），
     * 所以它们只能放行 / 限流 / 拒绝。资产出口不一样：<b>二次验证本来就长在这条链路上</b>
     * （{@code StepUpInterceptor} + 发码 / 验码两个接口 + 前端那个弹窗），
     * 所以风控可以直接给出 OTP —— 而且<b>可信设备也要验</b>。
     *
     * <p>那正是这个场景存在的意义：{@code MemberStepUpService.check} 回答的是
     * 「这台设备可信吗」，它不回答「这一次操作像不像出事了」。
     * 一台「验证过」的老设备被偷了会话之后，照样是「可信」的。
     *
     * <h3>处置的代价在这里是不对称的</h3>
     * OTP 是<b>可挽回</b>的（用户多收一封信、多输六位数），而 LIMIT / DENY 是硬拦。
     * 所以这个场景里新拍的阈值<b>给 OTP 档</b>就敢直接生效，给硬拦那两档的只有
     * 黑名单与设备封禁（人工签过字的结论）。
     */
    ASSET_OUT(5, "资产出口"),

    /**
     * 换绑联系方式（绑定 / 更换邮箱、手机号）。
     *
     * <h3>它是接管一个账号最彻底的一下</h3>
     * 换完之后原主连「找回密码」都走不通了 —— 挡着的只有那 7 天冷静期
     * （{@code ContactCoolingStore}）。所以这里要数的是
     * 「一台设备替几个人换过联系方式」：那是批量接管的样子，而不是家人互助的样子。
     *
     * <h3>🔴 这个场景要不到核身</h3>
     * 换绑本来就要「新地址的码」，而「证明你是原主」那一步对<b>首次绑定</b>压根不存在
     * （没有旧联系方式可问）—— 偏偏首次绑定才是那条接管链要用的口子。
     * 所以处置只能是放行 / 限流 / 拒绝，与注册、重置密码同形。
     */
    CONTACT_BIND(6, "换绑联系方式"),
    ;

    private final Integer value;

    private final String desc;
}
