package solvela.member.api;

/**
 * 风控对这一次资产出口的结论。<b>它只说结论，不说是哪条规则</b> ——
 * 调用方（网关的拦截器）据此决定返回哪个错误码。
 *
 * <h3>🔴 为什么不把 {@code MemberRiskDecisionEnum} 直接给网关</h3>
 * 那个枚举有七档，其中滑块、密码冷却在这条链路上<b>执行不了</b>。
 * 把它原样递出去，网关就得替域回答「这一档在资产出口上是什么意思」——
 * 而那正是域该收口的事。这里只给网关能执行的三种。
 *
 * @Date 2026-10-16
 */
public enum AssetOutRisk {

    /** 放行。风控没有意见 */
    PASS,

    /**
     * 要求先过二次验证，<b>可信设备也要</b>。
     *
     * <p>对客户端就是 {@code STEP_UP_REQUIRED} —— 与「新设备要验码」同一个码、同一个弹窗，
     * 所以这一档不需要前端做任何事。误判的代价也停在这里：用户多收一封信、多输六位数。
     */
    STEP_UP,

    /**
     * 硬拦。黑名单、设备封禁这类<b>人工签过字</b>的结论。
     *
     * <p>🔴 对外与限流同一句话（「操作过于频繁」），不说是不是被拉黑了 ——
     * 告诉对方具体原因等于给他一个精确的调试反馈。
     */
    BLOCKED,
}
