package solvela.member.api;

/**
 * 重置密码失败的原因。
 */
public enum PasswordResetFailReason {

    /** 邮箱格式不对。可以明说。 */
    BAD_EMAIL_FORMAT,

    /** 验证码没有 / 已过期。 */
    EMAIL_CODE_EXPIRED,

    /** 验证码错误。 */
    EMAIL_CODE_MISMATCH,

    /** 验证码错太多次，已作废。 */
    EMAIL_CODE_LOCKED,

    /** 新密码不符合强度要求。文案从 {@link MemberPasswordPolicy#HINT} 取，不在这里再写一遍。 */
    WEAK_PASSWORD,

    /**
     * 这个密码在<b>已泄露 / 极常见密码表</b>里（2026-10-16，方案 §9 P3 ③）。
     *
     * <h3>🔴 必须与「强度不够」分开说</h3>
     * 两者的补救办法完全不同：强度不够是「再加几位、加个数字」，
     * 而这一档是「这个密码本身不能用，换一个」。合成一句的话，
     * 用户会对着 {@code Password1} 反复加长度，而每一次都被拒 —— 他不会明白为什么。
     *
     * <p>⚠️ 文案里<b>不要</b>说「它在某某泄露库的第几名」：那是在教攻击者排序。
     */
    LEAKED_PASSWORD,


    /**
     * 这条联系方式是<b>在一台不受信任的设备上新绑的</b>，还在 7 天冷静期内，不能用来找回密码。
     *
     * <h3>🔴 三处拦截里后果最重的就是这一处</h3>
     * 用新绑的邮箱重置密码 = <b>永久接管</b>（改完密码，原主连验证码登录都进不来）。
     * 二次验证那一档漏了只是丢一次兑换，这一档漏了是丢整个账号。
     * 详见 {@code ContactCoolingStore}。
     */
    CONTACT_COOLING,

    // ------------------------------------------------------------------ 手机号找回（2026-09-10）

    /** 手机号格式不对。 */
    BAD_PHONE_FORMAT,

    /** 没有待校验的短信验证码：从没发过，或已过期。 */
    SMS_CODE_EXPIRED,

    /** 短信验证码错误。 */
    SMS_CODE_MISMATCH,

    /** 短信验证码连续输错次数用尽，已作废，必须重新发送。 */
    SMS_CODE_LOCKED,

    /**
     * 这个邮箱没有对应的会员。
     *
     * <h3>🔴 为什么这一档不构成账号枚举</h3>
     * 发码那一步对没有会员的邮箱<b>也存了码</b>（{@code MailDelivery.SUPPRESS}），
     * 而且那封信没寄出去 —— 也就是说要走到这一档，攻击者得先<b>猜中一个六位数</b>
     * （百万分之一，且只有 5 次机会）。在那之前他拿到的是与「有账号」逐字相同的
     * 验证码错误回答。
     */
    ACCOUNT_NOT_FOUND,

    /**
     * 被重置密码的限频挡下了。剩余秒数见 {@link MemberPasswordResetResult#retryAfterSeconds()}。
     *
     * <h3>🔴 它不说是哪一维被限，也不说是不是黑名单</h3>
     * 背后是四条规则（IP / 设备限频、IP 黑名单、设备封禁）。对外一律回
     * 「操作过于频繁」—— 告诉对方「你这个 IP 被拉黑了」等于给他一个精确的调试反馈。
     *
     * <p>⚠️ 这一档<b>必须给出等待秒数</b>：走到这里的人已经登不进账号了，
     * 而「请稍后再试」对他的意思是「不知道还有没有希望」。
     */
    TOO_MANY_ATTEMPTS,

    /**
     * 账号被冻结或已注销。
     *
     * <p>🔴 <b>冻结的账号不许自助找回</b>。允许的话，风控封掉一个刷子账号之后，
     * 他改个密码就能继续用 —— 而冻结的本意正是让他用不了。
     * 走到这一档说明他已经证明自己拥有这个邮箱，所以如实告知、引导找客服，
     * 判据同 {@link AuthFailReason#ACCOUNT_FROZEN}。
     */
    ACCOUNT_UNAVAILABLE,
}
