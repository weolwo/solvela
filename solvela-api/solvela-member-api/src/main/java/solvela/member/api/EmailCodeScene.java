package solvela.member.api;

/**
 * 邮箱验证码的<b>用途</b>。
 *
 * <h3>🔴 场景必须进 key，不能共用一个验证码</h3>
 * 共用的话，一个为「绑定邮箱」发出去的验证码就能拿去<b>重置密码</b>。
 * 攻击面很具体：诱导用户在某个页面走一次「绑定邮箱」（看起来人畜无害），
 * 拿到他念出来的那 6 位数，转手去重置他的密码。
 *
 * <p>所以四个场景各自一套 key、一套限频、<b>一封措辞不同的邮件</b> ——
 * 邮件里必须写清楚这个码是干什么用的，否则用户没有任何依据判断该不该念出来。
 *
 * <h3>匿名场景与已登录场景要分开限频</h3>
 * {@link #REGISTER} / {@link #LOGIN} / {@link #RESET_PASSWORD} 是<b>匿名</b>接口：
 * 任何人都能对着一个邮箱地址狂发，限频只能按邮箱和 IP 来。
 * {@link #BIND} 是<b>已登录</b>接口，还能按会员号限。
 *
 * <p>混成一套阈值的话，要么匿名那几条太松、要么绑定那条太紧。
 * 分开之后，「有人在对某个邮箱反复发重置密码邮件」这个信号才看得出来。
 */
public enum EmailCodeScene {

    /**
     * 注册。<b>验码即证明这个邮箱归他</b> —— 这是本项目第一条真正被验证过的身份通道
     * （手机号那条至今没有短信，任何人都能拿别人的号建账号）。
     */
    REGISTER,

    /** 免密登录。给「设过邮箱但忘了密码、又不想走重置流程」的用户。 */
    LOGIN,

    /** 已登录会员绑定/更换邮箱。 */
    BIND,

    /**
     * 重置密码。
     *
     * <p>⚠️ 这个场景的验证码<b>威力最大</b>：拿到它就能改密码，等于账号易主。
     * 所以它的失败次数上限、有效期都该比别的场景更紧，
     * 而且成功后必须吊销该会员的全部会话（见 {@code MemberTokenStore.revokeAll}）。
     */
    RESET_PASSWORD,

    /**
     * 敏感操作二次验证：在一台<b>不受信任的设备</b>上新增收货地址、充话费之前，
     * 证明「此刻操作的就是邮箱的主人」。见 {@link MemberStepUpApi}。
     *
     * <p>与其它场景的一个实质差别：<b>收码地址不由客户端给</b>，由域按会员号取他绑定的邮箱。
     * 让客户端填的话，偷到会话的人填自己的邮箱就把这道验证变成了自己给自己发码。
     * 同一个理由，它也没有「静默不寄」那一层 —— 调用方已登录，不存在账号枚举的问题。
     */
    STEP_UP,
}
