package solvela.member.api;

/**
 * 资产出口这一道闸的完整回答：<b>冻着没有</b> + <b>这台设备可信吗</b>。
 *
 * <h3>为什么两个答案合成一次调用</h3>
 * 守资产出口的拦截器两件事都要知道，而它们都在会员域里。分成两个接口的话，
 * 每一次「加地址 / 充话费」都要跨进程两趟 —— 而这两趟中间账号状态还可能变。
 *
 * <h3>🔴 顺序是固定的：先看冻结，再看信任</h3>
 * 冻结是「这个账号已经被认定出事了」，不管你在哪台设备上 ——
 * 包括那台受信任的老设备（举报的人很可能正拿着它）。
 * 反过来先判信任的话，老设备上的盗号者（会话被偷、设备已验证过）照样搬得走东西。
 *
 * @param frozen 资产出口是否冻结中（用户点过「这不是我」，重置密码后恢复）
 * @param trust  这台设备对这个会员的信任档位
 */
public record AssetOutVerdict(boolean frozen, DeviceTrust trust) {
}
