package solvela.member.api;

/**
 * 认证失败的原因。<b>会员域只回答「为什么失败」，不决定「告诉用户多少」。</b>
 *
 * <h3>为什么用返回值而不是抛异常</h3>
 * 认证失败是 C 端最常见的正常情况，不是异常事件。更要紧的是本枚举将来要跨进程：
 * 异常序列化过去只剩一个字符串，栈毫无意义，而调用方还得靠 catch 的类型去分支 ——
 * 那是把「业务失败」和「传输失败」混成一件事的开始。
 *
 * <h3>措辞留给调用方，是刻意的</h3>
 * 同一个 {@link #BAD_CREDENTIALS}，C 端要含糊成「手机号或密码错误」（分开说等于
 * 免费送出一个「这个号注册过没有」的查询接口），而内部工具和客服后台恰恰需要知道
 * 到底是查无此人还是密码不对。把文案钉死在域里，这两种需求只能满足一个。
 */
public enum AuthFailReason {

    /**
     * 手机号格式不对。<b>可以明说</b>：一个非法的串本来就不可能是任何人的手机号，不泄露任何信息。
     */
    BAD_PHONE_FORMAT,

    /**
     * 查无此人 / 已注销 / 密码错。<b>三者刻意合并成一个原因</b> —— 域内部区分得清清楚楚，
     * 但对外只给这一个值，让「分开告诉用户」这件事在类型层面就做不到。
     */
    BAD_CREDENTIALS,

    /**
     * 账号被冻结。走到这一步说明对方已经证明自己知道这个号是注册过的，
     * 再藏着只会让被误伤的用户一直重试然后打客服电话。
     */
    ACCOUNT_FROZEN,

    /**
     * 该账号从没设过密码（{@code t_member.password} 允许为空，是为验证码注册留的）。
     * 含糊其辞会让用户以为自己记错了密码，一直重试直到被限制。
     */
    NO_PASSWORD,

    /**
     * 连续失败次数过多，已被限制。剩余时长见 {@link MemberAuthResult#lockedSeconds()}。
     */
    OPERATION_LIMITED,

    /**
     * 这台<b>设备</b>被限了，与账号无关。剩余时长同样见 {@code lockedSeconds()}。
     *
     * <h3>为什么不并进 {@link #OPERATION_LIMITED}</h3>
     * 两者的解法完全不同，而用户要据此决定下一步做什么：
     * <ul>
     *   <li>账号被限 —— 是<b>这个号</b>连续输错密码，换台设备也一样被限；</li>
     *   <li>设备被限 —— 是<b>这台设备</b>上的行为异常（登录太频繁、碰过太多个号），
     *       换个号登录仍然会被限。</li>
     * </ul>
     * 合并的话，一个被设备维度限住的用户会一直去找回密码，而那件事解决不了他的问题。
     *
     * <p>⚠️ 对<b>真正的刷子</b>来说这条提示确实泄露了「你被设备维度盯上了」。
     * 这是权衡后接受的：误伤的正常用户（公司 NAT、共享平板）数量远大于刷子，
     * 而让他们对着一个查不出原因的失败反复重试，只会变成客服工单。
     */
    DEVICE_LIMITED,

    /**
     * 这个 IP 最近登录尝试过多（总次数、失败次数、或者对<b>不存在的账号</b>的尝试次数超限）。
     * 剩余秒数见 {@link MemberAuthResult#lockedSeconds()}。
     *
     * <p>与 {@link #DEVICE_LIMITED} 分开的理由相同：措辞要说清是「这个网络环境」而不是「你的账号」，
     * 否则用户会去找回密码，而那解决不了他的问题。它挡的是不带设备令牌、每次换账号的撞库脚本 ——
     * 那种脚本设备维度数不到、账号维度每个号只试一次，只剩 IP 这一个维度看得见。
     */
    IP_LIMITED,

    // ------------------------------------------------------------------ 邮箱验证码登录（2026-09-09）

    /**
     * 邮箱格式不对。与 {@link #BAD_PHONE_FORMAT} 同一个判据：可以明说，不泄露任何信息。
     */
    BAD_EMAIL_FORMAT,

    /**
     * 没有待校验的验证码：从没发过，或者已经过期。
     *
     * <h3>🔴 这一档为什么不会泄露「这个邮箱有没有账号」</h3>
     * 因为发码那一步<b>对没有账号的邮箱也照样存一个码</b>（只是不发信，
     * 见 {@code MailDelivery.SUPPRESS}）。两条路径的校验行为完全一样：
     * 有账号和没账号，输错码都得到 {@link #EMAIL_CODE_MISMATCH}。
     *
     * <p>不这么做的话，攻击者请求一次验证码、随便输个错码，
     * 看回的是「验证码错误」还是「验证码已失效」，就知道这人是不是本站用户 ——
     * 发码那一步藏住的东西，在校验这一步漏了出去。
     */
    EMAIL_CODE_EXPIRED,

    /** 验证码错误。剩余次数由域内部计数，用尽后转为 {@link #EMAIL_CODE_LOCKED}。 */
    EMAIL_CODE_MISMATCH,

    // ------------------------------------------------------------------ 设备观察档（2026-09-10）

    /**
     * 密码/验证码是对的，但<b>这台设备处在观察档</b>，还要再验一道验证码。
     *
     * <h3>🔴 这一档排在密码校验【之后】，是刻意的</h3>
     * 排在之前的话，任何人拿一个手机号就能让我们给机主发一条短信 ——
     * 而短信是花钱的，那就成了一个免费的短信轰炸接口。
     *
     * <p>代价是它<b>确认了密码是对的</b>：攻击者猜中密码时会看到这一档而不是
     * BAD_CREDENTIALS。这是所有二次验证共有的取舍 —— 他知道了密码对，
     * 但仍然进不去，因为他没有机主的手机。
     */
    DEVICE_VERIFICATION_REQUIRED,

    /**
     * 二次验证码给了，但不对 / 已失效 / 错太多次。
     *
     * <p>与 {@link #DEVICE_VERIFICATION_REQUIRED} 分开，是因为客户端要据此
     * 决定<b>弹输入框</b>还是<b>报错并让他重发</b> —— 判据同
     * {@code EmailBindFailReason} 的 REQUIRED / FAILED 那一对。
     */
    DEVICE_VERIFICATION_FAILED,

    /** 验证码连续输错次数用尽，已作废，必须重新发送。 */
    EMAIL_CODE_LOCKED
}
