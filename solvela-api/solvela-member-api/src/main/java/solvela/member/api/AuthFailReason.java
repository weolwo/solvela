package solvela.member.api;

/**
 * 认证失败的原因。<b>会员域只回答「为什么失败」，不决定「告诉用户多少」。</b>
 *
 * <h3>为什么用返回值而不是抛异常</h3>
 * 认证失败是 C 端最常见的正常情况，不是异常事件。更要紧的是本枚举将来要跨进程：
 * 异常序列化过去只剩一个字符串，栈毫无意义，而调用方还得靠 catch 的类型去分支 ——
 * 那是把「业务失败」和「传输失败」混成一件事的开始。
 *
 * <h3>措辞留给调用方，是刻意的</h3>
 * 同一个 {@link #BAD_CREDENTIALS}，C 端要含糊成「手机号或密码错误」（分开说等于
 * 免费送出一个「这个号注册过没有」的查询接口），而内部工具和客服后台恰恰需要知道
 * 到底是查无此人还是密码不对。把文案钉死在域里，这两种需求只能满足一个。
 */
public enum AuthFailReason {

    /**
     * 手机号格式不对。<b>可以明说</b>：一个非法的串本来就不可能是任何人的手机号，不泄露任何信息。
     */
    BAD_PHONE_FORMAT,

    /**
     * 查无此人 / 已注销 / 密码错。<b>三者刻意合并成一个原因</b> —— 域内部区分得清清楚楚，
     * 但对外只给这一个值，让「分开告诉用户」这件事在类型层面就做不到。
     */
    BAD_CREDENTIALS,

    /**
     * 账号被冻结。走到这一步说明对方已经证明自己知道这个号是注册过的，
     * 再藏着只会让被误伤的用户一直重试然后打客服电话。
     */
    ACCOUNT_FROZEN,

    /**
     * 该账号从没设过密码（{@code t_member.password} 允许为空，是为验证码注册留的）。
     * 含糊其辞会让用户以为自己记错了密码，一直重试直到被限制。
     */
    NO_PASSWORD,

    /**
     * 连续失败次数过多，已被限制。剩余时长见 {@link MemberAuthResult#lockedSeconds()}。
     */
    OPERATION_LIMITED
}
