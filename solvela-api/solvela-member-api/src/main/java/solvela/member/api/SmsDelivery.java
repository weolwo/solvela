package solvela.member.api;

/**
 * 这条短信到底发不发。与 {@code MailDelivery} 对称。
 *
 * <p>🔴 它<b>不影响返回给调用方的结果</b> —— 两种都是「成功」。
 * 回答不一样的话，发码接口就成了账号枚举器。
 */
public enum SmsDelivery {

    /** 真的发出去。 */
    DELIVER,

    /**
     * 存下码，但<b>不发</b>。
     *
     * <p>码照存、配额照扣，只是没有真的花钱、也没有真的响在别人手机上。
     * 照存是为了让「验码」那一侧的行为与正常情况完全一致 ——
     * 不存的话，攻击者能从「验码返回什么」反推出这个号有没有账号。
     */
    SUPPRESS,
}
