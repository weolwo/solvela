package solvela.member.api;

/**
 * 注册失败的原因。与 {@link AuthFailReason} 分开，因为两边该告诉用户多少<b>正好相反</b>。
 *
 * <h3>登录要含糊，注册必须明说</h3>
 * 登录时「查无此人」和「密码错」合并成一个 {@link AuthFailReason#BAD_CREDENTIALS}，
 * 为的是不让人拿登录接口枚举手机号。
 *
 * <p>注册反过来：{@link #PHONE_TAKEN} <b>必须</b>如实告诉用户，否则他不知道该去登录还是该换号，
 * 只会一直点注册。这确实构成一个手机号枚举口子 —— 但它是注册这件事本身自带的，
 * 藏不掉（藏了用户就没法用），只能靠 {@link #TOO_MANY_ATTEMPTS} 的限频把速率压下去。
 *
 * <p>🔴 所以别为了「安全」把 PHONE_TAKEN 改成含糊措辞：那不会减少泄露，
 * 只会让真实用户卡在注册页，而攻击者照样能从「注册成功与否」推出同样的信息。
 */
public enum RegisterFailReason {

    /**
     * 手机号格式不对。可以明说：一个非法的串本来就不可能是任何人的手机号，不泄露任何信息。
     */
    BAD_PHONE_FORMAT,

    /**
     * 手机号已注册。见类注释：必须明说。
     *
     * <p>注意「已注销」的账号<b>不算</b>已注册 —— 注销会把 {@code phone_hash} 置 NULL 释放号码，
     * 所以本人能用同一个号重新注册，这是 DDL 就设计好的。
     */
    PHONE_TAKEN,

    /**
     * 密码不满足强度要求。具体规则见会员域的 {@code MemberPasswordPolicy}，
     * <b>只有那一处</b> —— 前端只展示提示文案，不重写一遍规则。
     */
    WEAK_PASSWORD,

    /**
     * 被注册限频挡下了。剩余秒数见 {@link MemberRegisterResult#retryAfterSeconds()}。
     *
     * <h3>🔴 它不说是哪一维被限</h3>
     * 背后是四条规则：IP 限频、设备限频、IP 黑名单、设备封禁（2026-10-16 起都在风控引擎里）。
     * 对外<b>合成同一句</b>「操作过于频繁」—— 原来设备那一维回的是「当前设备操作过于频繁」，
     * 而那句话正好告诉了批量注册的人：该换设备，还是该换代理。
     *
     * <p>⚠️ 这几道闸都只能<b>压速率</b>，<b>拦不住定向占号</b>
     * （拿别人手机号抢注只需要成功一次）—— 那仍然只有验证码能解。
     */
    TOO_MANY_ATTEMPTS,

    // ------------------------------------------------------------------ 邮箱注册（2026-09-09）

    /** 邮箱格式不对。可以明说，判据同 {@link #BAD_PHONE_FORMAT}。 */
    BAD_EMAIL_FORMAT,

    /**
     * 该邮箱已被注册。
     *
     * <p>与 {@link #PHONE_TAKEN} 同一个取舍：<b>必须如实告诉用户</b>，
     * 否则他不知道该去登录还是该换个邮箱，只会一直点注册。
     * 这确实是个枚举口子，但它是注册这件事自带的、藏不掉。
     *
     * <p>🔴 邮箱这条比手机号那条<b>贵得多</b>：验证码校验排在查重<b>之前</b>，
     * 所以想枚举一个邮箱，先得证明你拥有它。手机号那条没有这道闸，
     * 只能靠限频压速率 —— 这正是「有验证码」和「没验证码」的实质差别。
     */
    EMAIL_TAKEN,

    /** 没有待校验的验证码：从没发过，或已过期。 */
    EMAIL_CODE_EXPIRED,

    /** 验证码错误。 */
    EMAIL_CODE_MISMATCH,

    /** 验证码连续输错次数用尽，已作废，必须重新发送。 */
    EMAIL_CODE_LOCKED,

    // ------------------------------------------------------------------ 手机号注册验证码（2026-09-10）

    /**
     * 没有待校验的短信验证码：从没发过，或已过期。
     *
     * <h3>🔴 这一档的出现，意味着手机号注册终于被验证了</h3>
     * 在它之前，任何人都能拿别人的手机号建账号 —— 而 {@code uk_mbr_phone_hash}
     * 是唯一约束，号被占了真机主就再也注册不了。那段话在
     * {@code MemberRegisterService} 的类注释上挂了整整一个月。
     */
    SMS_CODE_EXPIRED,

    /** 短信验证码错误。 */
    SMS_CODE_MISMATCH,

    /** 短信验证码连续输错次数用尽，已作废，必须重新发送。 */
    SMS_CODE_LOCKED
}
