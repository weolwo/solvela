package solvela.app.ratelimit;

/**
 * 匿名场景的请求体实现它，交出「这次请求针对的是哪个账号」的原始输入（邮箱或手机号）。
 *
 * <p>用接口而不是在注解里写表达式：表达式写错了是运行期才发现的（而且只表现为「账号维度从不计数」），
 * 接口写错了编译不过。网关只拿它来<b>计数</b>：规范化之后算 HMAC 当键，格式对不对仍由会员域判。
 *
 * <p>已登录的请求不调它 —— 那时的账号就是会员号本人。
 *
 * @Date 2026-10-17
 */
public interface RateLimitAccount {

    /** 原始输入；为空表示这次请求没有可数的账号（只按 IP、设备等维度数） */
    String rateLimitAccount();
}
