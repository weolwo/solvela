package solvela.member.risk;

/**
 * 有副作用的处置动作。<b>决策只说结论，动作单独列出来</b>（方案 §3.8）。
 *
 * <h3>🔴 为什么要和决策分开</h3>
 * 陪跑中的规则也会执行。如果规则自己去降设备档、自己去写限制表，那「陪跑」就名存实亡 ——
 * 一条还在观察的规则已经在改线上数据了。所以规则只能<b>请求</b>一个动作，
 * 由引擎按<b>生效的</b>结论统一执行；陪跑命中带的动作一律丢掉。
 *
 * <h3>动作从哪来</h3>
 * <ul>
 *   <li><b>规则级</b>：规则在 {@code RiskHit.withActions} 里声明（降设备档、写限制表）；</li>
 *   <li><b>结论级</b>：{@link #NOTIFY_OWNER} 由引擎按最终结论加，它不属于任何单条规则 ——
 *       「这次登录可疑到该通知主人」是几条规则叠起来的结果。</li>
 * </ul>
 *
 * @Date 2026-10-15
 */
public enum RiskAction {

    /**
     * 把这台设备降进观察档（24 小时内登录要多验一道码）。
     *
     * <p>对应现状 {@code DeviceGuard.hit} 里的 {@code dispositionService.observe}。
     * 由设备闸那几条规则在 {@code params.observe = true} 时请求。
     */
    OBSERVE_DEVICE,

    /**
     * 给主人发一封「我们拦下了一次可疑登录」。与新设备登录提醒同一套模板机制。
     *
     * <p>🔴 <b>信里不放任何链接</b>（全景图鉴：带链接的安全提醒就是钓鱼）。
     */
    NOTIFY_OWNER,

    /**
     * 往 {@code t_member_operation_limit} 写一行，让这次限制在后台可见、可人工解除。
     *
     * <p>只有长冷却（默认 60 分钟及以上）才请求它：60 秒那档也落库的话，
     * 那张表会被手滑的人刷满，而客服要找的恰恰是「被锁了很久」的那几个人。
     */
    RECORD_LIMIT,
}
