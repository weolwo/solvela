package solvela.marketing.api;

/**
 * 兑换没被受理的原因。域只给 reason，<b>说什么由接入层决定</b> ——
 * 同一个 {@code OUT_OF_STOCK}，C 端要说「手慢了，已被兑完」，
 * 内部工具要看到的是事实本身。与抽奖那条链路同一套分工。
 *
 * <p>🔴 调用方用 switch 表达式接，<b>别写 default</b>：
 * 这里新增一个值时那边编译不过，而不是悄悄显示成「操作失败」。
 */
public enum MallRedeemReason {

    /** SKU 不存在。用户拿了个过期页面或伪造的 id */
    SKU_NOT_FOUND,

    /** 商品已下架 / 不在上架有效期内。与「不存在」合并，对用户是同一件事 */
    COMMODITY_OFF,

    /**
     * 会员等级不够，这是件专享商品。
     *
     * <p>⚠️ 不要和 {@code COMMODITY_OFF} 合并：那两件事对用户的<b>下一步动作完全不同</b> ——
     * 下架了只能换一件，等级不够是「再攒一攒就能换」。
     * 而后者正是这套等级体系要换的东西，把它说成「兑不了」等于把动机抹掉。
     *
     * <p>接入层应当把<b>差多少</b>说出来（还差哪一档），而不是只说一句「等级不足」。
     */
    GRADE_NOT_ENOUGH,

    /** 库存不够（或 SKU 已停用） */
    OUT_OF_STOCK,

    /** 超出限兑次数 */
    EXCHANGE_LIMITED,

    /** 积分不足。接入层应当算出差额告诉用户 */
    POINTS_NOT_ENOUGH,

    /** 钱包被冻结 */
    WALLET_UNAVAILABLE,

    /** 余额并发变动，<b>可重试</b>。别和「积分不足」合并成同一句提示 */
    CONCURRENT_CONFLICT,

    /** 实物商品没传收货地址 */
    ADDRESS_REQUIRED,

    /** 地址不存在或不属于这个会员（软引用，用户可能刚把它删了） */
    ADDRESS_NOT_FOUND,

    /**
     * 券用不了：过期了、被别的单锁着、已经用掉了、或者不满足这一单的条件。
     *
     * <p>⚠️ 几种情况合并成一个原因是刻意的：对用户都是「这张券用不了，换一张」。
     * 分得更细只会让文案变成一份需要维护的状态机，而用户的下一步动作是同一个。
     * 真要排查，日志里有具体状态。
     */
    COUPON_UNUSABLE,

    /*
     * 2026-09-15 阶段 6 删掉了 COUPON_NOT_SUPPORTED。
     *
     * 它当时只有一个生产者：POINTS_CASH 订单用券会被直接拒 —— 因为那种单落在
     * 待支付，而支付回调一行代码都没有，没有任何地方能把券从「锁定中」推到
     * 「已使用」。假支付（MallPayService）补上了那个确认点之后，这条拒绝没有了
     * 生产者，留着就是一个永远不会发生的分支。
     */

    /** 我们自己的问题。对用户是「服务出问题了」，不是「你填错了」 */
    INTERNAL
}
